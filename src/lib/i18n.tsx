const DICTIONARIES: Record<Lang, Strings> = { uz, ru, en };

export type TKey = keyof Strings;

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

function readStoredLang(): Lang {
  if (typeof window === "undefined") return "uz";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "uz" || stored === "ru" || stored === "en" ? stored : "uz";
}

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  locale: string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* storage may be blocked in private mode */
    }
  }, []);

  const value = useMemo<I18nValue>(() => {
    const table = DICTIONARIES[lang];
    return {
      lang,
      setLang,
      locale: LANGUAGES.find((l) => l.code === lang)?.locale ?? "uz-UZ",
      t: (key, vars) => interpolate(table[key] ?? uz[key] ?? String(key), vars),
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

/** API xato kodini tarjima qilingan xabarga aylantiradi. */
export function errorMessage(t: I18nValue["t"], error: unknown): string {
  if (error instanceof TypeError) return t("err.network");
  const code =
    error && typeof error === "object" && "code" in error
      ? String((error as { code: string }).code)
      : "";
  if (code.startsWith("http_")) return t("err.service_unavailable");
  const key = `err.${code}` as TKey;
  return key in uz ? t(key) : t("err.unknown");
}
